/*
 * sample_data.c - fictional demo records for "sbdf.exe --demo".
 * Owner: Developer 4 (enlarged to 200 donors and 120 patients).
 *
 * Everything is added through records_add_donor / records_add_patient so the
 * normal validation (and the duplicate-id check) applies to the demo data too.
 * ALL NAMES AND PHONE NUMBERS ARE INVENTED.
 *
 * HOW THE DATA IS BUILT
 *   1. The first 12 donors (ids 101-112) and the first 8 patients (ids 1-8)
 *      are the original hand-made records, kept exactly as they were. They are
 *      a small example that is easy to follow on paper.
 *   2. The remaining records are GENERATED by simple formulas from the lists
 *      below (names, cities, blood groups). There is no random number, so every
 *      run produces exactly the same data.
 *   3. To change the amount of data, edit TOTAL_DONORS and TOTAL_PATIENTS.
 *      Ids stay unique automatically: donors are 101, 102, ... and patients
 *      are 1, 2, ...
 *
 * WHAT THE HAND-MADE RECORDS DEMONSTRATE
 *   Scenario 1 - several blood groups and cities.
 *   Scenario 2 - an augmenting-path reassignment. Patient 1 (A-) can use donor
 *       101 (O-) or donor 102 (A-). A greedy "first free donor" rule gives her
 *       donor 101, which patient 2 (O-) also needs. Kuhn's algorithm moves
 *       patient 1 to donor 102 and gives donor 101 to patient 2.
 *   Scenario 3 - patients 2 and 7 are both O- and compete for O- donors.
 *   Scenario 4 - donor 107 (O-) is compatible but UNAVAILABLE, so no edge.
 *   Scenario 5 - donor 108 (AB+) can only donate to AB+ patients.
 *   NOTE: the generated records add many more edges, so the final matching on
 *   the full data set is different from the 12-donor / 8-patient example.
 *   Generated unavailable donors (about 1 in 9) keep Scenario 4 going on a
 *   bigger scale.
 *
 * WHY THE ORDER OF THE RECORDS MATTERS
 *   Kuhn's algorithm visits patients in store order and tries donors in store
 *   order, so the first patient normally grabs the first donor that fits.
 */

